import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { deflateSync } from "node:zlib";

const VALID_TARGET = /^[A-Za-z0-9._-]+$/;

function cppBytes(bytes) {
  const width = 20;
  const lines = [];
  for (let i = 0; i < bytes.length; i += width) {
    lines.push(
      "  " + Array.from(bytes.subarray(i, i + width), (value) => `0x${value.toString(16).padStart(2, "0")}`).join(", "),
    );
  }
  return lines.join(",\n");
}

function cppString(value) {
  return JSON.stringify(value);
}

async function discoverTargets(root) {
  let entries;
  try {
    entries = await readdir(root, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") {
      return [];
    }
    throw error;
  }

  const targets = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }
    if (!VALID_TARGET.test(entry.name)) {
      throw new Error(
        `Invalid game target directory ${JSON.stringify(entry.name)}. ` +
        "Target names may contain only letters, numbers, '.', '_' and '-'.",
      );
    }

    const file = resolve(root, entry.name, "nwscript.nss");
    try {
      const data = await readFile(file);
      if (data.length === 0) {
        throw new Error(`Embedded language spec is empty: ${file}`);
      }
      const compressed = deflateSync(data, { level: 9 });
      targets.push({ name: entry.name, file, data, compressed });
    } catch (error) {
      if (error?.code !== "ENOENT") {
        throw error;
      }
    }
  }

  targets.sort((a, b) => a.name.localeCompare(b.name));
  return targets;
}

export async function generateGameTargets({ projectRoot, outDir }) {
  const targetRoot = resolve(
    projectRoot,
    process.env.NWSC_GAME_TARGETS_DIR ?? "games",
  );
  const requested = (process.env.NWSC_GAME_TARGETS ?? "")
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean);

  const discovered = await discoverTargets(targetRoot);
  const byName = new Map(discovered.map((target) => [target.name, target]));

  let selected = discovered;
  if (requested.length > 0) {
    const unique = [...new Set(requested)];
    const missing = unique.filter((name) => !byName.has(name));
    if (missing.length > 0) {
      throw new Error(
        `Requested embedded game target(s) not found: ${missing.join(", ")}. ` +
        `Expected <target>/nwscript.nss under ${targetRoot}`,
      );
    }
    selected = unique.map((name) => byName.get(name));
  }

  await mkdir(outDir, { recursive: true });
  const output = resolve(outDir, "embedded_game_targets.cpp");

  const arrays = selected.map((target, index) => `
static const uint8_t kTargetData${index}[] = {
${cppBytes(target.compressed)}
};`).join("\n");

  const rows = selected.length > 0
    ? selected.map((target, index) =>
        `  {${cppString(target.name)}, kTargetData${index}, sizeof(kTargetData${index}), ${target.data.length}},`
      ).join("\n")
    : "  {nullptr, nullptr, 0, 0},";

  const source = `// Generated by scripts/generate-game-targets.mjs. Do not edit.
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <vector>
#include <zlib.h>

#ifdef __EMSCRIPTEN__
#include <emscripten/emscripten.h>
#define NWSC_EMBED_EXPORT EMSCRIPTEN_KEEPALIVE
#else
#define NWSC_EMBED_EXPORT
#endif

namespace {
struct EmbeddedTarget {
  const char* name;
  const uint8_t* data;
  size_t compressedSize;
  size_t uncompressedSize;
  std::vector<uint8_t> decompressed;
};
${arrays}

static EmbeddedTarget kTargets[] = {
${rows}
};
static constexpr size_t kTargetCount = ${selected.length};
}

extern "C" {
NWSC_EMBED_EXPORT size_t nwsc_embedded_target_count() {
  return kTargetCount;
}

NWSC_EMBED_EXPORT const char* nwsc_embedded_target_name(size_t index) {
  return index < kTargetCount ? kTargets[index].name : nullptr;
}

NWSC_EMBED_EXPORT const uint8_t* nwsc_embedded_target_data(const char* name) {
  if (name == nullptr) return nullptr;
  for (size_t i = 0; i < kTargetCount; ++i) {
    if (std::strcmp(kTargets[i].name, name) != 0) continue;

    EmbeddedTarget& target = kTargets[i];
    if (target.decompressed.empty()) {
      target.decompressed.resize(target.uncompressedSize);
      uLongf outputSize = static_cast<uLongf>(target.uncompressedSize);
      const int result = uncompress(
          target.decompressed.data(),
          &outputSize,
          target.data,
          static_cast<uLong>(target.compressedSize));
      if (result != Z_OK || outputSize != target.uncompressedSize) {
        target.decompressed.clear();
        return nullptr;
      }
    }
    return target.decompressed.data();
  }
  return nullptr;
}

NWSC_EMBED_EXPORT size_t nwsc_embedded_target_size(const char* name) {
  if (name == nullptr) return 0;
  for (size_t i = 0; i < kTargetCount; ++i) {
    if (std::strcmp(kTargets[i].name, name) == 0) return kTargets[i].uncompressedSize;
  }
  return 0;
}
}
`;

  await writeFile(output, source);
  return {
    sourceFile: output,
    targetRoot,
    targets: selected.map(({ name, file, data, compressed }) => ({
      name,
      file,
      size: data.length,
      compressedSize: compressed.length,
    })),
  };
}
